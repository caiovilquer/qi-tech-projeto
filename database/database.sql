	creation_idempotency_key UUID NOT NULL,
	creation_request JSONB NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT clock_timestamp() NOT NULL,
	PRIMARY KEY (id),
	UNIQUE (creation_integrator, creation_idempotency_key),
	CHECK (balance_cents BETWEEN 0 AND 9007199254740991),
	CHECK (status IN ('PENDING','ACTIVE','REJECTED','BLOCKED')),
	CHECK (status_version > 0),
	CHECK (status NOT IN ('PENDING','REJECTED') OR balance_cents=0),
	UNIQUE (account_key),
	FOREIGN KEY(customer_id) REFERENCES customer (id) ON DELETE RESTRICT
);
