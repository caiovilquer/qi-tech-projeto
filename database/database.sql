CREATE TABLE customer (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 1),
	customer_key UUID NOT NULL,
	customer_type VARCHAR(2) NOT NULL,
	document_number VARCHAR(14) NOT NULL,
	name VARCHAR(120) NOT NULL,
	email VARCHAR(254),
	creation_integrator VARCHAR(120) NOT NULL,
	creation_idempotency_key UUID NOT NULL,
	creation_request JSONB NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT clock_timestamp() NOT NULL,
	PRIMARY KEY (id),
	UNIQUE (creation_integrator, creation_idempotency_key),
	UNIQUE (customer_type, document_number),
	CHECK (customer_type IN ('PF','PJ')),
	CHECK (length(trim(name)) > 0),
	CHECK ((customer_type='PF' AND document_number ~ '^[0-9]{11}$') OR (customer_type='PJ' AND document_number ~ '^[A-Z0-9]{12}[0-9]{2}$')),
	UNIQUE (customer_key)
);
